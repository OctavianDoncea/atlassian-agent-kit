from __future__ import annotations
import json
import logging
from typing import Any
from openai import OpenAI
from agentkit.config import get_settings

logger = logging.getLogger(__name__)

class JudgeResult:
    def __init__(self, passed: bool, reasoning: str):
        self.passed = passed
        self.reasoning = reasoning


def exact_match(expected: dict, actual: dict) -> JudgeResult:
    if expected == actual:
        return JudgeResult(True, 'Exact match')
    
    return JudgeResult(False, f'Mismatch.\nExpected: {expected}\nActual: {actual}')

def subset_match(expected: dict, actual: dict) -> JudgeResult:
    for k, v in expected.items():
        if k not in actual:
            return JudgeResult(False, f"Missing key '{k}'. Expected {v}.")
        if actual[k] != v:
            return JudgeResult(False, f"Mismatched key '{k}'. Expected {v}, got {actual[k]}.")

    return JudgeResult(True, 'All expected parameters present.')

def semantic_judge(prompt: str, expected_tool: str, expected_params: dict, actual_tool: str, actual_params: dict, model: str | None = None) -> JudgeResult:
    settings = get_settings()
    if not settings.groq_api_key:
        return JudgeResult(False, 'Cannot run semantic judge without GROQ_API_KEY.')

    model = model or settings.judge_llm_model

    system_prompt = """You are an expert evaluator for AI tool-calling agents. Compare the EXPECTED tool and parameters with the ACTUAL tool and parameters generated by an agent.
                    Determine if they are semantically equivalent and would achieve the same result for the user's prompt. Respond ONLY in valid JSON format: {"passed": true/false, "reasoning": "brief explanation"}"""

    user_prompt = f"""User prompt: {prompt}
                    Expected tool: {expected_tool}
                    Expected parameters: {expected_params}
                    Actual tool: {actual_tool}
                    Actual parameters: {json.dumps(actual_params)}"""

    try:
        client = OpenAI(api_key=settings.groq_api_key, base_url=settings.llm_base_url)
        response = client.chat.completions.create(
            model=model,
            messages=[
                {'role': 'system', 'content': system_prompt},
                {'role': 'user', 'content': user_prompt}
            ],
            response_format={'type': 'json_object'},
            temperature=0.0
        )
        content = response.choices[0].message.content or ''
        data = json.loads(content)
        
        return JudgeResult(bool(data.get('passed', False)), data.get('reasoning', 'No reasoning provided.'))
    except Exception as e:
        logger.error(f'Judge LLM failed: {e}')
        return JudgeResult(False, f'Judge LLM error: {e}')

def evaluate_case(case: dict, actual_tool: str | None, actual_params: dict) -> JudgeResult:
    if actual_tool != case.get('expected_tool'):
        return JudgeResult(False, f'Wrong tool selected. Expected {case.get('expected_tool')}, got {actual_tool}.')

    expected_params = case.get('expected_params', {})
    mode = case.get('judge_mode', 'exact_match')

    if mode == 'exact_match':
        return exact_match(expected_params, actual_params)
    if mode == 'subset_match':
        return subset_match(expected_params, actual_params)
    if mode == 'semantic_jql':
        return semantic_judge(case.get('prompt', ''), case['expected_tool'], expected_params, actual_tool, actual_params)

    return JudgeResult(False, f'Unknown judge mode: {mode}')